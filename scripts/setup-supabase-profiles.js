/**
 * scripts/setup-supabase-profiles.js
 * 
 * Establishes Supabase as the Single Source of Truth for Chrome Profiles and Sender Accounts.
 * Creates the sender_profiles table and seeds default accounts.
 */
require('dotenv').config();
const db = require('../src/config/db');

async function setupSenderProfiles() {
    console.log('?? Ensuring sender_profiles table exists in Supabase...');

    const createTableSql = `
        CREATE TABLE IF NOT EXISTS sender_profiles (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email VARCHAR(255) UNIQUE NOT NULL,
            display_name VARCHAR(255),
            profile_folder VARCHAR(255) NOT NULL,
            daily_quota INT DEFAULT 500,
            sent_today INT DEFAULT 0,
            status VARCHAR(50) DEFAULT 'READY',
            last_used_at TIMESTAMPTZ,
            notes TEXT,
            created_at TIMESTAMPTZ DEFAULT NOW(),
            updated_at TIMESTAMPTZ DEFAULT NOW()
        );
    `;

    try {
        await db.query(createTableSql);
        console.log('? Table sender_profiles verified/created.');

        // Seed initial sender accounts
        const seedSql = `
            INSERT INTO sender_profiles (email, display_name, profile_folder, daily_quota, status)
            VALUES 
                ('editor@worldwidejournals.co.in', 'Worldwide Journals Editor', 'chrome-profile', 500, 'READY'),
                ('editorial@researchworldwidejournals.com', 'Research Worldwide Editorial', 'chrome-profile-editorial', 500, 'READY')
            ON CONFLICT (email) DO UPDATE SET
                display_name = EXCLUDED.display_name,
                profile_folder = EXCLUDED.profile_folder,
                status = EXCLUDED.status,
                updated_at = NOW();
        `;

        await db.query(seedSql);
        console.log('? Default sender profiles seeded/synchronized.');

        const [rows] = await db.query('SELECT id, email, display_name, profile_folder, status FROM sender_profiles ORDER BY id ASC');
        console.log('\n?? Current Active Profiles in Supabase:');
        rows.forEach(r => {
            console.log(`   - [ID ${r.id}] ${r.email} -> Folder: "${r.profile_folder}" (Status: ${r.status})`);
        });

    } catch (err) {
        console.error('? Failed to setup sender_profiles:', err.message);
        process.exit(1);
    } finally {
        if (db && db.end) await db.end().catch(() => {});
    }
}

if (require.main === module) {
    setupSenderProfiles();
}

module.exports = setupSenderProfiles;
